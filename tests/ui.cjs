const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const artifacts=path.join(__dirname,'..','test-artifacts');fs.mkdirSync(artifacts,{recursive:true});
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1080}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(process.env.DEMO_URL||'http://127.0.0.1:5000');
 await page.fill('#password',process.env.ADMIN_PASSWORD);
 await page.click('button[type=submit]');
 await page.waitForFunction(()=>document.querySelector('#online-count')?.textContent==='5',{timeout:20000});
 page.on('dialog',d=>d.accept());
 await page.click('#reset');
 await page.waitForFunction(()=>document.querySelector('#detected-count').textContent==='0');
 await page.click('#run-all');
 await page.waitForFunction(()=>document.querySelector('#prevented-count').textContent==='4',null,{timeout:60000});
 await page.waitForFunction(()=>!document.querySelector('#run-all').disabled,null,{timeout:60000});
 assert.equal(await page.locator('.event').count(),12);
 const state=await page.evaluate(()=>fetch('/api/state').then(r=>r.json()));
 assert.equal(state.runs.filter(r=>r.status==='completed').length,3);
 assert.equal(state.metrics.critical,1);
 assert.ok(state.events.some(e=>e.event_type==='virtualization_threat'&&e.stage==='prevented'&&e.node_id!==e.source_node));
 await page.waitForFunction(()=>document.querySelector('#run-status').textContent.startsWith('Verified'));
 await page.screenshot({path:path.join(artifacts,'dashboard-desktop.png'),fullPage:true});
 await page.click('[data-stage=prevented]');assert.equal(await page.locator('.event').count(),4);
 await page.selectOption('#severity-filter','critical');assert.equal(await page.locator('.event').count(),1);
 await page.selectOption('#severity-filter','all');await page.click('[data-stage=all]');
 await page.click('[data-view=controls]');assert.ok(await page.locator('#controls-section').isVisible());
 await page.click('[data-view=events]');assert.equal(await page.locator('#scenario-section').isVisible(),false);
 const download=page.waitForEvent('download');await page.click('#export');assert.equal((await download).suggestedFilename(),'aegis-events.json');
 await page.click('[data-view=overview]');
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:path.join(artifacts,'dashboard-mobile.png'),fullPage:true});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'Mobile horizontal overflow');
 assert.deepEqual(errors,[]);
 await page.setViewportSize({width:1440,height:1080});
 // Keep real, generated rehearsal results visible for the user.
 console.log('UI PASS: login, five nodes, full scenario sequence, destination evidence, filters, navigation, JSON export, mobile layout; no JS errors.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
